@click.group()
def cli():
    pass


@cli.command("create-pr")
@click.option("--branch", required=True, help="Feature branch name")
@click.option("--jira-id", required=True, help="Jira ticket ID (e.g. DATA-123)")
@click.option("--base", default="main", help="Base branch to merge into")
@click.option(
    "--repo",
    default=None,
    help="owner/repo to target -- defaults to $GITHUB_REPO. Pass the repo opsbuddy-fix's "
    "get-repo-mapping resolved when it differs from the configured default.",
)
@click.option(
    "--body-file",
    default=None,
    help="Path to file containing PR body (skips auto-generation)",
)
def cmd_create_pr(
    branch: str, jira_id: str, base: str, repo: Optional[str], body_file: Optional[str]
):
    """Create a GitHub PR from the current branch, linked to a Jira ticket."""
    try:
        jira = JiraClient()
        ticket = jira.get_ticket(jira_id)
    except Exception as e:
        logger.warning(f"Could not fetch Jira ticket: {e}")
        ticket = None

    summary = ticket.summary if ticket else branch
    title = f"[{jira_id}] {summary}"

    if body_file:
        with open(body_file, "r", encoding="utf-8") as f:
            body = f.read()
    else:
        description = ticket.description if ticket else ""
        diff_stat = get_git_diff_summary()
        body = build_pr_body(jira_id, summary, description, diff_stat)

    gh = GitHubClient(repo=repo)
    pr = gh.create_pr(branch=branch, title=title, body=body, base=base)
    click.echo(f"[OK] PR created: {pr.html_url}")

    if ticket:
        # Try "In Review" first; fall back to "In Progress" if unavailable
        for transition_name in ("In Review", "In Progress"):
            try:
                jira.transition_ticket(jira_id, transition_name)
                click.echo(f"[OK] Jira {jira_id} transitioned to '{transition_name}'")
                break
            except ValueError:
                continue
        jira.add_comment(jira_id, f"PR created: {pr.html_url}")


@cli.command("review-pr")
@click.option("--pr-number", required=True, type=int, help="PR number")
@click.option(
    "--repo", default=None, help="owner/repo to target -- defaults to $GITHUB_REPO"
)
def cmd_review_pr(pr_number: int, repo: Optional[str]):
    """Show PR status and CI check results."""
    gh = GitHubClient(repo=repo)
    pr = gh.get_pr(pr_number)
    checks = gh.get_pr_checks(pr_number)

    console.print(f"\n[bold]PR #{pr_number}[/bold]: {pr.title}")
    console.print(f"State: {pr.state} | Mergeable: {pr.mergeable}")
    console.print(f"URL: {pr.html_url}\n")

    for check in checks:
        icon = "[OK]" if check["conclusion"] == "success" else "[FAIL]"
        click.echo(f"  {icon} {check['name']}: {check['conclusion']}")


@cli.command("merge-pr")
@click.option("--pr-number", required=True, type=int, help="PR number")
@click.option("--jira-id", default=None, help="Jira ticket ID to close after merge")
@click.option(
    "--method", default="squash", type=click.Choice(["merge", "squash", "rebase"])
)
@click.option(
    "--repo", default=None, help="owner/repo to target -- defaults to $GITHUB_REPO"
)
def cmd_merge_pr(
    pr_number: int, jira_id: Optional[str], method: str, repo: Optional[str]
):
    """Merge a PR and optionally close the Jira ticket."""
    gh = GitHubClient(repo=repo)
    gh.merge_pr(pr_number, merge_method=method)
    click.echo(f"[OK] PR #{pr_number} merged")

    if jira_id:
        jira = JiraClient()
        jira.transition_ticket(jira_id, "Done")
        jira.add_comment(jira_id, f"PR #{pr_number} merged to main. Ticket closed.")
        click.echo(f"[OK] Jira {jira_id} closed")


@cli.command("clone")
@click.option(
    "--repo-url",
    required=True,
    help="Git URL to clone (e.g. https://github.com/org/repo.git)",
)
@click.option("--target-dir", required=True, help="Local directory to clone into")
def cmd_clone(repo_url: str, target_dir: str):
    """Clone a repo into a local working directory."""
    GitRepoManager.clone(repo_url, target_dir)
    click.echo(f"[OK] Cloned into {target_dir}")


@cli.command("create-branch")
@click.option("--repo-dir", required=True, help="Path to the local clone")
@click.option("--branch", required=True, help="New branch name")
@click.option("--base", default="main", help="Base branch to branch from")
def cmd_create_branch(repo_dir: str, branch: str, base: str):
    """Create a new branch off `base` in an existing local clone."""
    GitRepoManager(repo_dir).create_branch(branch, base=base)
    click.echo(f"[OK] Branch {branch} created from {base}")


@cli.command("commit")
@click.option("--repo-dir", required=True, help="Path to the local clone")
@click.option("--message", required=True, help="Commit message")
@click.option(
    "--files",
    required=True,
    multiple=True,
    help="File path(s) to stage — repeat the flag, or pass a comma-separated list",
)
def cmd_commit(repo_dir: str, message: str, files: tuple):
    """Stage and commit specific files in an existing local clone."""
    file_list = [f.strip() for group in files for f in group.split(",") if f.strip()]
    sha = GitRepoManager(repo_dir).commit(message, file_list)
    click.echo(f"[OK] Committed {sha}")


@cli.command("push")
@click.option("--repo-dir", required=True, help="Path to the local clone")
@click.option("--branch", required=True, help="Branch name to push")
@click.option("--remote", default="origin", help="Remote name")
def cmd_push(repo_dir: str, branch: str, remote: str):
    """Push a branch from a local clone to the remote."""
    GitRepoManager(repo_dir).push(branch, remote=remote)
    click.echo(f"[OK] Pushed {branch} to {remote}")


@cli.command("check-access")
def cmd_check_access():
    """Verify GITHUB_TOKEN can see GITHUB_REPO and has push access (fast preflight check)."""
    result = GitHubClient().check_access()
    click.echo(
        f"[OK] Repo: {result['repo']} (default branch: {result['default_branch']})"
    )
    if result["push_access"]:
        click.echo("[OK] Push access: yes")
    else:
        click.echo("[WARN] Push access: no — clone/push/PR steps will likely fail")


if __name__ == "__main__":
    cli()
